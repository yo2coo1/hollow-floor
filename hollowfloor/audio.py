"""Sound design + mix. Every effect is synthesized here with numpy (no third-party audio files),
so the source of every sound is this file. Voice stays loudest; the bed ducks under it; the final mix is loudness-normalized."""
import json
import os
import subprocess
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.signal import fftconvolve, lfilter

SR = 24000
FFMPEG = os.environ.get("FFMPEG_PATH", "ffmpeg")
SOURCE_NOTE = "self-generated by hollowfloor/audio.py (numpy synthesis)"


def _rng(seed):
    return np.random.default_rng(seed)


def _lowpass(x, cutoff):
    a = np.exp(-2 * np.pi * cutoff / SR)  # one-pole filter
    return lfilter([1 - a], [1, -a], x).astype(np.float32)


def _env(n, attack, release):
    e = np.ones(n, np.float32)
    a, r = int(attack * SR), int(release * SR)
    if a: e[:a] = np.linspace(0, 1, a)
    if r: e[-r:] *= np.exp(-np.linspace(0, 6, r))
    return e


# ---------- effects (all short mono float32 arrays) ----------
def _band(x, lo, hi):
    return _lowpass(x, hi) - _lowpass(x, lo)


def footstep(seed=0):
    """Shoe on a hard floor: sharp heel strike, then a softer toe tap ~70 ms later. Varied per step so a walk never repeats."""
    r = _rng(seed); n = int(0.3 * SR); t = np.arange(n) / SR
    out = np.zeros(n, np.float32)
    for at, amp in ((0.0, 1.0), (0.06 + r.random() * 0.03, 0.45)):
        s = int(at * SR); m = n - s; tt = t[:m]
        click = _band(r.standard_normal(m).astype(np.float32), 250 + r.random() * 100, 1600 + r.random() * 600) * np.exp(-tt / 0.006)
        body = np.sin(2 * np.pi * (95 + r.random() * 25) * tt) * np.exp(-tt / 0.022) * 0.5
        out[s:] += (click * 1.3 + body) * amp
    scuff = _band(r.standard_normal(n).astype(np.float32), 800, 3000) * np.exp(-t / 0.04) * 0.08
    return (out + scuff).astype(np.float32) * (0.8 + 0.4 * r.random())


def _room(x, seconds=0.7, seed=9):
    """Small-room echo: convolve with a short decaying noise burst so effects sit in the space instead of on top of it."""
    n = int(seconds * SR); t = np.arange(n) / SR
    ir = _lowpass(_rng(seed).standard_normal(n).astype(np.float32), 3000) * np.exp(-t / 0.13)
    ir[0] = 0
    wet = fftconvolve(x, ir)[: len(x)]
    return (wet / (np.abs(wet).max() + 1e-9) * np.abs(x).max()).astype(np.float32)


def creak(seconds=1.4, seed=1):
    n = int(seconds * SR); t = np.arange(n) / SR; r = _rng(seed)
    f = 220 + 140 * np.sin(2 * np.pi * 0.7 * t) + 30 * np.cumsum(r.standard_normal(n)) / np.sqrt(n)
    phase = 2 * np.pi * np.cumsum(f) / SR
    saw = 2 * ((phase / (2 * np.pi)) % 1) - 1
    grain = (r.random(n) > 0.6).astype(np.float32)  # stick-slip friction texture
    return (_lowpass((saw * grain).astype(np.float32), 2500) * _env(n, 0.05, 0.3) * 0.7).astype(np.float32)


def hit(seed=2):
    """The one sharp scare sound: sub drop + noise burst + dissonant stab."""
    n = int(1.6 * SR); t = np.arange(n) / SR; r = _rng(seed)
    sub = np.sin(2 * np.pi * np.cumsum(120 * np.exp(-t * 2.5) + 35) / SR) * np.exp(-t * 1.8)
    burst = _lowpass(r.standard_normal(n).astype(np.float32), 3000) * np.exp(-t * 9)
    stab = sum(np.sin(2 * np.pi * f * t) for f in (311, 330, 466)) / 3 * np.exp(-t * 3)
    return (sub * 0.9 + burst * 0.6 + stab * 0.35).astype(np.float32)


def buzz(seconds=1.0, seed=3):
    """Fluorescent flicker buzz: 120 Hz hum gated randomly."""
    n = int(seconds * SR); t = np.arange(n) / SR; r = _rng(seed)
    hum = np.sign(np.sin(2 * np.pi * 120 * t)) * 0.3 + np.sin(2 * np.pi * 240 * t) * 0.2
    gate = np.repeat(r.random(n // 600 + 1) > 0.4, 600)[:n]
    return (_lowpass((hum * gate).astype(np.float32), 1500) * 0.5).astype(np.float32)


def knock(seed=4):
    out = np.zeros(int(0.9 * SR), np.float32)
    for k, at in enumerate((0.0, 0.28, 0.56)):
        n = int(0.12 * SR); s = int(at * SR); t = np.arange(n) / SR
        out[s:s + n] += (np.sin(2 * np.pi * 110 * t) * 0.8 + _lowpass(_rng(seed + k).standard_normal(n).astype(np.float32), 900) * 0.5) * np.exp(-t * 40)
    return out


def ring(seconds=2.0):
    """Classic phone ring cadence (440+480 Hz)."""
    n = int(seconds * SR); t = np.arange(n) / SR
    tone = (np.sin(2 * np.pi * 440 * t) + np.sin(2 * np.pi * 480 * t)) * 0.25
    gate = ((t % 0.1) < 0.05) & (t < 1.6)  # warbling bell
    return (tone * gate).astype(np.float32)


EFFECTS = {"footstep": footstep, "creak": creak, "hit": hit, "buzz": buzz, "knock": knock, "ring": ring}


def _bed(n, seed=7):
    """Room tone + low drone with slow movement. Sits under everything."""
    t = np.arange(n) / SR; r = _rng(seed)
    room = _lowpass(r.standard_normal(n).astype(np.float32), 400) * 0.06
    drone = (np.sin(2 * np.pi * 55 * t) + 0.6 * np.sin(2 * np.pi * 55.7 * t) + 0.3 * np.sin(2 * np.pi * 82.4 * t)) * (0.6 + 0.4 * np.sin(2 * np.pi * 0.07 * t))
    return (room + drone * 0.05).astype(np.float32)


def mix(voice_wav, out_wav, duration=None, events=(), voice_meta=None):
    """events: [{"t", "type", "gain"?, "until"? (footsteps/buzz span), "every"? (footstep interval)}]."""
    voice, sr = sf.read(voice_wav, dtype="float32")
    assert sr == SR, sr
    n = int((duration or len(voice) / SR) * SR)
    v = np.zeros(n, np.float32); v[:min(n, len(voice))] = voice[:n]

    # duck the bed while the narrator speaks
    env = np.convolve(np.abs(v), np.ones(int(0.2 * SR)) / int(0.2 * SR), mode="same")
    duck = 1 - 0.55 * np.clip(env / (env.max() + 1e-6) * 4, 0, 1)
    bed = _bed(n) * duck * _env(n, 1.0, 0.8)

    fx = np.zeros(n, np.float32)
    for e in events:
        kind, gain = e["type"], e.get("gain", 0.5)
        if kind == "footsteps":
            times = np.arange(e["t"], e["until"], e.get("every", 0.55))
            jit = _rng(int(e["t"] * 100)).uniform(-0.04, 0.04, len(times))  # humans don't walk on a metronome
            clips = [(max(0, tt + j), footstep(int(tt * 100))) for tt, j in zip(times, jit)]
            gain = e.get("gain", 0.1)  # owner feedback 2026-11-14: footsteps were too loud
        elif kind == "buzz":
            clips = [(e["t"], buzz(e["until"] - e["t"]))]
        else:
            clips = [(e["t"], EFFECTS[kind]())]
        for tt, c in clips:
            s = int(tt * SR); c = c[: max(0, n - s)]
            fx[s:s + len(c)] += c * gain

    fx = fx * 0.75 + _room(fx) * 0.4
    out = v * 1.0 + bed + fx
    raw = Path(out_wav).with_suffix(".raw.wav")
    out = out / max(1e-6, np.abs(out).max()) * 0.95
    sf.write(raw, np.stack([out, out], axis=1), SR)  # stereo before measuring, so measured == delivered loudness
    # -14 LUFS integrated, -1.5 dBTP: the common target for Shorts/Reels/TikTok, so every video plays at the same level
    # two-pass: measure, then apply a linear gain (one-pass undershoots on short clips)
    target = "I=-14:TP=-1.5:LRA=11"
    p = subprocess.run([FFMPEG, "-hide_banner", "-i", str(raw), "-af", f"loudnorm={target}:print_format=json", "-f", "null", "-"],
                       capture_output=True, text=True, check=True)
    m = json.loads(p.stderr[p.stderr.rindex("{"):p.stderr.rindex("}") + 1])
    # plain gain to -14 LUFS, then a limiter at -1.5 dBFS catches the scare-hit peaks (loudnorm's linear mode refuses when peaks are high)
    af = f"volume={-14 - float(m['input_i']):.2f}dB,alimiter=limit=0.78:level=false:attack=2:release=60"
    subprocess.run([FFMPEG, "-y", "-loglevel", "error", "-i", str(raw), "-af", af, "-ar", "48000", str(out_wav)], check=True)
    raw.unlink()
    Path(out_wav).with_suffix(".sources.json").write_text(json.dumps({
        "voice": voice_meta or "unknown", "room_tone_and_drone": SOURCE_NOTE,
        "effects": sorted({e["type"] for e in events}), "effects_source": SOURCE_NOTE,
    }, indent=1))
    return out_wav
